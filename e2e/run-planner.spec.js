test('imported conditions stay separate until following the calculator; invalid snapshot cannot overwrite the workspace',async({page})=>{
  await ready(page);await page.locator('#open-run-planner').click();
  await page.locator('#run-planner details').filter({has:page.locator('#plan-save')}).locator('summary').click();
  const download=page.waitForEvent('download');await page.locator('#plan-export').click();await download;
  const saved=JSON.parse(await page.locator('#plan-json').inputValue());
  saved.context={...saved.context,targetType:'ceramic',camo:true,fortified:true,aura:true,early:true,criticalMode:'expected'};
  saved.source.artifactVersion=0;
  await page.locator('#plan-json').fill(JSON.stringify(saved));await page.locator('#plan-import').click();
  await expect(page.locator('#plan-context')).toContainText('Ceramic · Camo · Fortified');
  await expect(page.locator('#plan-context')).toContainText('saved plan battle conditions (early, aura)');
  await expect(page.locator('#plan-storage-status')).toContainText('The source differs');
  await expect(page.locator('#live-stat-context')).toContainText('Boss');
  const before=await page.locator('#plan-baselines').textContent();
  saved.setup.stages[2].componentId='missing';
  await page.locator('#plan-json').fill(JSON.stringify(saved));await page.locator('#plan-import').click();
  await expect(page.locator('#plan-storage-status')).toContainText('Current plan unchanged');
  expect(await page.locator('#plan-baselines').textContent()).toBe(before);
  await page.locator('#plan-follow-context').check();await expect(page.locator('#plan-context')).toContainText('Boss');
  await expect(page.locator('#plan-context')).toContainText('current battle conditions');
});

