  await page.locator('#plan-tower').selectOption('Ninja Monkey');
  await stage(page,1,'path').selectOption('200');await stage(page,2,'path').selectOption('300');
  await page.locator('#plan-artifact').selectOption('SwiftestToBusiness');
  await expect(page.locator('#plan-offer-summary')).toContainText('First modeled benefit: Late');
  await expect(page.locator('#plan-offer-results tr').first()).toContainText('Defer modeled benefit to Late');
  await expect(page.locator('#plan-offer-results tr').last()).toContainText('Consider if offered');
  await page.locator('#plan-rarity').selectOption('Rare');
  await page.locator('#plan-add-loadout').click();
  await expect(page.locator('#plan-offer-summary')).toContainText('Already in the starting loadout');
  await page.locator('#plan-starting-loadout > summary').click();
  await expect(page.locator('#plan-loadout')).toContainText('Swiftest To Business');
  await page.locator('#plan-rarity').selectOption('Common');await page.locator('#plan-add-loadout').click();
  await expect(page.locator('#plan-loadout li')).toHaveCount(1);
  expect(await page.evaluate(()=>localStorage.getItem('rogue-lab-v1'))).toBe(before);
  expect(await page.locator('#undo-build').isDisabled()).toBe(undoDisabled);
