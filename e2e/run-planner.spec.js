for(const width of [1440,390])test(`complete plan ${width}: chosen picks, save/reload, download and atomic import`,async({page},testInfo)=>{
  await page.setViewportSize({width,height:900});await ready(page);await page.locator('#open-run-planner').click();
  const current=await page.evaluate(()=>localStorage.getItem('rogue-lab-v1'));
  await page.locator('#plan-artifact').selectOption('SlowerIsHarder');
  await page.locator('#plan-pick-mid').click();
  await expect(page.locator('#plan-baselines tr').first()).not.toContainText('Slower Is Harder');
  await expect(page.locator('#plan-baselines tr').nth(1)).toContainText('Slower Is Harder · Common');
  await expect(page.locator('#plan-baselines tr').last()).toContainText('Slower Is Harder · Common');
  await page.locator('#plan-rarity').selectOption('Rare');await page.locator('#plan-pick-late').click();
  await expect(page.locator('#plan-baselines tr').last()).toContainText('Slower Is Harder · Rare');
  await page.locator('#plan-priority').selectOption('pierce');
  await page.locator('#run-planner details').filter({has:page.locator('#plan-save')}).locator('summary').click();
  await page.locator('#plan-save').click();await expect(page.locator('#plan-storage-status')).toContainText('Complete plan saved');
  const downloadPromise=page.waitForEvent('download');await page.locator('#plan-export').click();const download=await downloadPromise;
  expect(download.suggestedFilename()).toBe('rogue-lab-run-plan.json');
  const file=await download.path();const {readFile}=await import('node:fs/promises');const json=await readFile(file,'utf8');
  expect(JSON.parse(json).setup.stages[2].acquired.SlowerIsHarder).toBe('Rare');
  expect(await page.evaluate(()=>localStorage.getItem('rogue-lab-v1'))).toBe(current);
  await page.reload();await page.locator('#open-run-planner').click();
  await expect(page.locator('#plan-priority')).toHaveValue('pierce');
  await expect(page.locator('#plan-follow-context')).not.toBeChecked();
  await expect(page.locator('#plan-baselines tr').last()).toContainText('Slower Is Harder · Rare');
  await page.locator('#plan-chosen-details > summary').click();
  await page.locator('[data-plan-unpick="SlowerIsHarder"][data-stage="1"]').click();
  await expect(page.locator('#plan-baselines tr').nth(1)).not.toContainText('Slower Is Harder');
  await expect(page.locator('#plan-baselines tr').last()).toContainText('Slower Is Harder · Rare');
  await page.locator('#run-planner details').filter({has:page.locator('#plan-save')}).locator('summary').click();
  await page.locator('#plan-json').fill('{"version":999}');await page.locator('#plan-import').click();
  await expect(page.locator('#plan-storage-status')).toContainText('Current plan unchanged');
  await expect(page.locator('#plan-baselines tr').nth(1)).not.toContainText('Slower Is Harder');
  await page.locator('#plan-file').setInputFiles({name:'plan.json',mimeType:'application/json',buffer:Buffer.from(json)});
  await page.locator('#plan-import').click();
  await expect(page.locator('#plan-baselines tr').nth(1)).toContainText('Slower Is Harder · Common');
  await expect(page.locator('#plan-rarity')).toHaveValue('Rare');
  expect(await page.evaluate(()=>localStorage.getItem('rogue-lab-v1'))).toBe(current);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:testInfo.outputPath('complete-plan.png')});
});

